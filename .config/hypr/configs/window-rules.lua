-- https://wiki.hypr.land/configuring/core/rules/window-rules/

-- Ignore maximize requests from all apps. You'll probably like this.
hl.window_rule({
    name  = "suppress-maximize-events",
    match = { class = ".*" },

    suppress_event = "maximize",
})

-- Fix some dragging issues with XWayland
hl.window_rule({
    name  = "fix-xwayland-drags",
    match = {
        class      = "^$",
        title      = "^$",
        xwayland   = true,
        float      = true,
        fullscreen = false,
        pin        = false,
    },

    no_focus = true,
})

-- Hyprland-run
hl.window_rule({
    name  = "move-hyprland-run",
    match = { class = "hyprland-run" },

    move  = "20 monitor_h-120",
    float = true,
})

-- Allow tearing for these games (only takes effect with general.allow_tearing = true)
hl.window_rule({ name = "tearing-cs2",   match = { class = "cs2" },   immediate = true })
hl.window_rule({ name = "tearing-dota2", match = { class = "dota2" }, immediate = true })
